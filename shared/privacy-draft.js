function renderAdminPrivacyView(){
  const el = document.getElementById('admin-privacy-content');
  if (!el) return;
    let html = '', inList = false;
  PRIVACY_DRAFT['pt-BR'].forEach(([kind, v]) => {
    if (kind !== 'li' && inList){ html += '</ul>'; inList = false; }
    if (kind === 'h') html += `<h3 class="privacy-draft-h">${escapeHTML(v)}</h3>`;
    else if (kind === 'li'){ if (!inList){ html += '<ul class="privacy-draft-list">'; inList = true; } html += `<li>${escapeHTML(v)}</li>`; }
    else if (kind === 'table') html += `<div class="privacy-draft-scroll"><table class="privacy-draft-table"><thead><tr>${v.head.map(c => `<th>${escapeHTML(c)}</th>`).join('')}</tr></thead><tbody>${v.rows.map(r => `<tr>${r.map(c => `<td>${escapeHTML(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
    else html += `<p class="privacy-draft-p">${escapeHTML(v)}</p>`;
  });
  if (inList) html += '</ul>';
  el.innerHTML = `<div class="privacy-draft">${html}</div>`;
}
