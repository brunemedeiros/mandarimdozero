function renderAdminPrivacyView(){
  const el = document.getElementById('admin-privacy-content');
  if (!el) return;
  const lang = (typeof getUiLang === 'function' && getUiLang() === 'pt-BR') ? 'pt-BR' : 'en';
  const blocks = PRIVACY_DRAFT[lang];
  let html = '', inList = false;
  blocks.forEach(([kind, text]) => {
    if (kind !== 'li' && inList){ html += '</ul>'; inList = false; }
    if (kind === 'h') html += `<h3 class="privacy-draft-h">${escapeHTML(text)}</h3>`;
    else if (kind === 'li'){ if (!inList){ html += '<ul class="privacy-draft-list">'; inList = true; } html += `<li>${escapeHTML(text)}</li>`; }
    else html += `<p class="privacy-draft-p">${escapeHTML(text)}</p>`;
  });
  if (inList) html += '</ul>';
  el.innerHTML = `<div class="privacy-draft">${html}</div>`;
}
